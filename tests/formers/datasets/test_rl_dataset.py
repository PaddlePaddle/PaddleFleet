"""Behavior tests for paddlefleet.datasets.rlhf_datasets.rl_dataset.

These tests use small, content-distinguishable inputs and hand-derived
expected results (never generated by calling the code under test). They cover:

* left_padding places real content on the RIGHT and pad tokens on the LEFT,
  honours an explicit max_length, the supplied pad value, and the input dtype.
* padding_batch_data left-pads prompts to max_prompt_len but pads labels only
  to the per-batch max label length, keeps raw lengths accurate, and only
  emits label fields when requires_label is set.
* collate_fn preserves the padded content and exposes the prompt/length keys.
* RLHFDataset builds each sample by tokenizing the correct field (prompt_key
  vs response_key), truncates the prompt to max_prompt_len, routes list-shaped
  prompts through apply_chat_template when enabled, and caches lazily so a
  second access reuses the first result instead of re-tokenizing.

load_dataset is isolated with a real in-memory list of records (an external
data source, not the logic under test). The tokenizer is a real
content-preserving fake so that assertions can distinguish which text was
encoded, not merely that encoding occurred.
"""

import unittest
from unittest.mock import patch

import numpy as np

from paddlefleet.datasets.rlhf_datasets.rl_dataset import (
    RLHFDataset,
    collate_fn,
    left_padding,
    padding_batch_data,
)

MODULE = "paddlefleet.datasets.rlhf_datasets.rl_dataset"


class FakeTokenizer:
    """Content-preserving fake tokenizer.

    Maps each character of the input text to its ordinal, so the produced
    input_ids are a deterministic, content-distinguishable function of the
    exact string that was tokenized. This lets the tests assert *which* field
    (prompt vs response) was encoded and whether truncation / chat-template
    transformations were applied, rather than only that tokenization happened.
    """

    def __init__(self, model_max_length=1024, chat_template=None):
        self.model_max_length = model_max_length
        self.chat_template = chat_template
        self.tokenize_calls = 0
        self.chat_template_inputs = []

    def __call__(
        self,
        text,
        add_special_tokens=True,
        padding=None,
        max_length=None,
        truncation=True,
        return_tensors="np",
    ):
        self.tokenize_calls += 1
        ids = [ord(ch) for ch in text]
        if truncation and max_length is not None:
            ids = ids[:max_length]
        return {"input_ids": np.array([ids])}

    def apply_chat_template(
        self, messages, add_generation_prompt=True, tokenize=False
    ):
        self.chat_template_inputs.append(
            (messages, add_generation_prompt, tokenize)
        )
        # Deterministic, distinguishable transform of the raw message list.
        joined = "|".join(m["content"] for m in messages)
        return "T:" + joined


class TestLeftPadding(unittest.TestCase):
    """left_padding pads on the LEFT, keeping content right-aligned."""

    def test_content_is_right_aligned_and_pad_on_left(self):
        # If padding were on the right, row 1 would be [4, 5, 0]; the
        # right-aligned expectation is what distinguishes left padding.
        result = left_padding(
            [np.array([1, 2, 3]), np.array([4, 5])], padding_value=0
        )
        self.assertEqual(result.shape, (2, 3))
        np.testing.assert_array_equal(result[0], [1, 2, 3])
        np.testing.assert_array_equal(result[1], [0, 4, 5])

    def test_three_sequences_distinguishable_content(self):
        result = left_padding(
            [np.array([7]), np.array([8, 9]), np.array([1, 2, 3, 4])],
            padding_value=0,
        )
        expected = np.array(
            [
                [0, 0, 0, 7],
                [0, 0, 8, 9],
                [1, 2, 3, 4],
            ]
        )
        np.testing.assert_array_equal(result, expected)

    def test_custom_pad_value_fills_left(self):
        result = left_padding(
            [np.array([7, 8]), np.array([9])], padding_value=-100
        )
        np.testing.assert_array_equal(result, [[7, 8], [-100, 9]])

    def test_explicit_max_length_pads_all_rows_on_left(self):
        result = left_padding([np.array([1, 2])], padding_value=0, max_length=5)
        self.assertEqual(result.shape, (1, 5))
        np.testing.assert_array_equal(result[0], [0, 0, 0, 1, 2])

    def test_dtype_follows_first_sequence(self):
        seqs = [
            np.array([1, 2, 3], dtype=np.int64),
            np.array([4], dtype=np.int64),
        ]
        result = left_padding(seqs, padding_value=0)
        self.assertEqual(result.dtype, np.int64)
        np.testing.assert_array_equal(result[1], [0, 0, 4])


class TestPaddingBatchData(unittest.TestCase):
    """Prompts pad to max_prompt_len; labels pad to the batch-max length."""

    def test_prompts_left_padded_to_max_prompt_len(self):
        samples = [
            {"input_ids": np.array([11, 12, 13])},
            {"input_ids": np.array([21, 22])},
        ]
        result = padding_batch_data(
            samples, pad_token_id=0, requires_label=False, max_prompt_len=5
        )
        # Both rows widen to max_prompt_len (5), content right-aligned.
        np.testing.assert_array_equal(
            result["input_ids"],
            [[0, 0, 11, 12, 13], [0, 0, 0, 21, 22]],
        )
        # raw_prompt_len records the ORIGINAL (pre-pad) lengths.
        self.assertEqual(result["raw_prompt_len"].tolist(), [3, 2])
        self.assertNotIn("label_ids", result)
        self.assertNotIn("raw_label_ids_len", result)

    def test_labels_pad_to_batch_max_not_max_prompt_len(self):
        # Prompts and labels share lengths [3, 2], but max_prompt_len is 5.
        # Prompts therefore widen to 5 while labels widen only to the batch
        # max of 3 -- a distinguishing behavior between the two fields.
        samples = [
            {
                "input_ids": np.array([11, 12, 13]),
                "label_ids": np.array([31, 32, 33]),
            },
            {
                "input_ids": np.array([21, 22]),
                "label_ids": np.array([41, 42]),
            },
        ]
        result = padding_batch_data(
            samples, pad_token_id=0, requires_label=True, max_prompt_len=5
        )
        np.testing.assert_array_equal(
            result["input_ids"],
            [[0, 0, 11, 12, 13], [0, 0, 0, 21, 22]],
        )
        np.testing.assert_array_equal(
            result["label_ids"],
            [[31, 32, 33], [0, 41, 42]],
        )
        self.assertEqual(result["input_ids"].shape, (2, 5))
        self.assertEqual(result["label_ids"].shape, (2, 3))
        self.assertEqual(result["raw_prompt_len"].tolist(), [3, 2])
        self.assertEqual(result["raw_label_ids_len"].tolist(), [3, 2])

    def test_pad_token_id_fills_prompt_padding(self):
        samples = [
            {"input_ids": np.array([11, 12, 13])},
            {"input_ids": np.array([21])},
        ]
        result = padding_batch_data(
            samples, pad_token_id=7, requires_label=False, max_prompt_len=3
        )
        np.testing.assert_array_equal(
            result["input_ids"],
            [[11, 12, 13], [7, 7, 21]],
        )


class TestCollateFn(unittest.TestCase):
    """collate_fn preserves padded content and exposes prompt/length keys."""

    def test_collate_preserves_left_padded_prompts(self):
        samples = [
            {"input_ids": np.array([11, 12, 13])},
            {"input_ids": np.array([21, 22])},
        ]
        result = collate_fn(
            samples, pad_token_id=0, requires_label=False, max_prompt_len=4
        )
        np.testing.assert_array_equal(
            result["input_ids"].numpy(),
            [[0, 11, 12, 13], [0, 0, 21, 22]],
        )
        self.assertEqual(result["raw_prompt_len"].tolist(), [3, 2])

    def test_collate_with_labels_keeps_both_fields(self):
        samples = [
            {
                "input_ids": np.array([11, 12, 13]),
                "label_ids": np.array([31, 32, 33]),
            },
            {
                "input_ids": np.array([21, 22]),
                "label_ids": np.array([41, 42]),
            },
        ]
        result = collate_fn(
            samples, pad_token_id=0, requires_label=True, max_prompt_len=5
        )
        np.testing.assert_array_equal(
            result["input_ids"].numpy(),
            [[0, 0, 11, 12, 13], [0, 0, 0, 21, 22]],
        )
        np.testing.assert_array_equal(
            result["label_ids"].numpy(),
            [[31, 32, 33], [0, 41, 42]],
        )
        self.assertEqual(result["raw_label_ids_len"].tolist(), [3, 2])


class TestRLHFDataset(unittest.TestCase):
    """Sample construction: correct field, truncation, chat template, cache."""

    def _build(self, rawdata, tokenizer, **kwargs):
        # load_dataset is an external data source; replace it with the real
        # in-memory records so the dataset's own indexing/caching logic runs.
        with (
            patch(f"{MODULE}.os.path.exists", return_value=True),
            patch(f"{MODULE}.load_dataset", return_value=list(rawdata)),
        ):
            return RLHFDataset(
                dataset_name_or_path="/tmp/rl_data.json",
                tokenizer=tokenizer,
                **kwargs,
            )

    def test_len_matches_number_of_records(self):
        tok = FakeTokenizer()
        ds = self._build([{"src": "a"}, {"src": "b"}, {"src": "c"}], tok)
        self.assertEqual(len(ds), 3)

    def test_getitem_tokenizes_prompt_field(self):
        tok = FakeTokenizer()
        ds = self._build([{"src": "hi"}], tok)
        item = ds[0]
        # ord('h')=104, ord('i')=105 -> proves 'hi' (the prompt) was encoded.
        np.testing.assert_array_equal(item["input_ids"], [104, 105])
        self.assertNotIn("label_ids", item)

    def test_getitem_uses_custom_prompt_key_not_default(self):
        tok = FakeTokenizer()
        ds = self._build(
            [{"question": "Q!", "src": "WRONG"}], tok, prompt_key="question"
        )
        item = ds[0]
        # ord('Q')=81, ord('!')=33 -> 'Q!' from prompt_key, not 'WRONG'.
        np.testing.assert_array_equal(item["input_ids"], [81, 33])

    def test_getitem_truncates_prompt_to_max_prompt_len(self):
        tok = FakeTokenizer()
        ds = self._build([{"src": "abcde"}], tok, max_prompt_len=3)
        item = ds[0]
        # 'abcde' -> [97, 98, 99, 100, 101] truncated to the first 3.
        np.testing.assert_array_equal(item["input_ids"], [97, 98, 99])

    def test_getitem_with_label_encodes_response_field(self):
        tok = FakeTokenizer()
        ds = self._build(
            [{"src": "hi", "answer": "yo"}],
            tok,
            requires_label=True,
            response_key="answer",
            max_prompt_len=4,
        )
        item = ds[0]
        # prompt 'hi' -> [104,105]; label 'yo' -> [121,111] from response_key.
        np.testing.assert_array_equal(item["input_ids"], [104, 105])
        np.testing.assert_array_equal(item["label_ids"], [121, 111])

    def test_label_not_truncated_by_max_prompt_len(self):
        # Only the prompt is bounded by max_prompt_len; the label is tokenized
        # with the tokenizer's model_max_length, so a long response survives.
        tok = FakeTokenizer(model_max_length=1024)
        ds = self._build(
            [{"src": "abcde", "answer": "wxyz"}],
            tok,
            requires_label=True,
            response_key="answer",
            max_prompt_len=2,
        )
        item = ds[0]
        np.testing.assert_array_equal(item["input_ids"], [97, 98])
        # 'wxyz' -> [119,120,121,122], untouched by max_prompt_len=2.
        np.testing.assert_array_equal(item["label_ids"], [119, 120, 121, 122])

    def test_getitem_applies_chat_template_for_list_prompt(self):
        tok = FakeTokenizer(chat_template="present")
        messages = [{"role": "user", "content": "hi"}]
        ds = self._build([{"src": messages}], tok, apply_chat_template=True)
        item = ds[0]
        # apply_chat_template turns the messages into 'T:hi', which then
        # tokenizes to ord('T'),ord(':'),ord('h'),ord('i').
        np.testing.assert_array_equal(item["input_ids"], [84, 58, 104, 105])
        self.assertEqual(len(tok.chat_template_inputs), 1)
        passed_messages, add_gen, tokenize = tok.chat_template_inputs[0]
        self.assertEqual(passed_messages, messages)
        self.assertTrue(add_gen)
        self.assertFalse(tokenize)

    def test_getitem_skips_chat_template_when_tokenizer_has_none(self):
        # apply_chat_template requested, but tokenizer.chat_template is falsy,
        # so the raw string prompt is tokenized directly.
        tok = FakeTokenizer(chat_template=None)
        ds = self._build([{"src": "hi"}], tok, apply_chat_template=True)
        item = ds[0]
        np.testing.assert_array_equal(item["input_ids"], [104, 105])
        self.assertEqual(tok.chat_template_inputs, [])

    def test_second_access_returns_cached_result_without_retokenizing(self):
        tok = FakeTokenizer()
        ds = self._build([{"src": "hi"}], tok)
        # Lazily populated: before access the slot holds the sentinel.
        self.assertIs(ds.data[0], RLHFDataset._SENTINEL)

        first = ds[0]
        self.assertEqual(tok.tokenize_calls, 1)
        np.testing.assert_array_equal(first["input_ids"], [104, 105])

        second = ds[0]
        # Same cached object, and no additional tokenizer invocation.
        self.assertIs(second, first)
        self.assertEqual(tok.tokenize_calls, 1)


if __name__ == "__main__":
    unittest.main()
